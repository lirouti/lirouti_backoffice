/**
 * 둥지 — 발밑 단계 (docs/ARCHITECTURE.md §41.3).
 *
 * **엔티티인데 폴더가 아니라 파일인 이유**: 규칙이 하나도 없다. 3단계가 기획으로 고정돼 있어
 * 운영자가 늘리거나 고치지 않는다 — 등록·수정 화면을 만들지 않은 것도 같은 이유다.
 * 4번째를 만들면 해금 일수 구간이 겹치고, 클라이언트에 그 연출이 없다.
 *
 * ⚠️ **배경이 아니라 오브젝트다.** 원본: 「둥지는 배경이 아니라 발밑에 놓이는 오브젝트입니다.
 *    어떤 배경으로 옮겨도 함께 따라다닙니다.」 그래서 배경과 좌표계가 같고(`0 0 586 576`)
 *    단독으로 보면 아래쪽에만 그려져 있다 (§8.6).
 */
export type Nest = {
  /** 에셋 파일 id — 'as_nest_0' */
  assetId: string
  /** 「잔가지 둥지」 */
  name: string
  /** 카드에 붙는 설명 — 「누적 1–29일 · 성글게 엮인 첫 둥지」 */
  sub: string
  /** 표의 「해금 조건」 — 「누적 1–29일」 */
  cond: string
  /** 표의 「소품」. 없으면 `'—'` (빈 문자열이 아니다 — 표에서 칸이 비면 누락으로 읽힌다) */
  props: string
  /** 보유율 (%) */
  own: number
}
