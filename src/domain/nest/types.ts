/**
 * 둥지 — 발밑 단계 (docs/ARCHITECTURE.md §41.3).
 *
 * **3단계가 기획으로 고정이다.** 4번째를 만들면 해금 일수 구간이 겹치고 클라이언트에 그
 * 연출이 없다. 대신 **그림과 해금 일수는 바뀐다**(§19.3).
 *
 * ⚠️ **배경이 아니라 오브젝트다.** 원본: 「둥지는 배경이 아니라 발밑에 놓이는 오브젝트입니다.
 *    어떤 배경으로 옮겨도 함께 따라다닙니다.」 그래서 배경과 좌표계가 같고(`0 0 586 576`)
 *    **단독으로 보면 아래쪽에만 그려져 있다** — 미리보기를 배경 위에 얹는 이유다 (§41.5).
 */
import type { AssetExt } from '../asset'

export type Nest = {
  /**
   * 줄을 가리키는 **고정 id**. 늘지도 줄지도 않는 집합이라 값이 바뀌지 않는다.
   *
   * ⚠️ **`assetId` 를 식별자로 쓰지 말 것.** 그림 교체가 열리면서 `assetId` 는 **바뀌는
   *    값**이 됐다 — 카탈로그의 다른 그림을 고르면 다른 줄과 같은 id 가 되어 React 키가
   *    겹치고, 파사드가 **엉뚱한 줄을 고친다** (docs/ARCHITECTURE.md §19.3.2).
   */
  key: number
  /** 지금 그림의 에셋 id — `as_nest_0`. **교체되는 값이다** */
  assetId: string
  /** 「잔가지 둥지」 */
  name: string
  /**
   * 이 둥지가 해금되는 누적 일수. **끝나는 날은 저장하지 않는다** — 다음 둥지의
   * `fromDay` 에서 나온다 (§25.1 과 같은 규칙).
   */
  fromDay: number
  /** 카드 설명의 뒷부분 — 「성글게 엮인 첫 둥지」. **일수는 여기 넣지 않는다** */
  desc: string
  /** 표의 「소품」. 없으면 `'—'` (빈 문자열이 아니다 — 표에서 칸이 비면 누락으로 읽힌다) */
  props: string
  /**
   * 올린 그림의 URL. **파사드가 실어 준다**(`withAssetSrc`) — 올린 에셋은 빌드에 없어
   * `assetId` 로 못 찾기 때문이다 (docs/ARCHITECTURE.md §8.5).
   *
   * 비어 있으면 빌드 에셋이라는 뜻이다.
   */
  assetSrc?: string
  /** 그림의 파일 형식. 없으면 빌드 에셋이라 SVG 다 */
  assetExt?: AssetExt
  /** 보유율 (%) */
  own: number
}

/** 운영자가 고치는 값. 첫 둥지는 언제나 1일차부터라 경계가 아니다 */
export type NestBoundaries = {
  /** 두 번째 둥지가 해금되는 날 */
  secondFrom: number
  /** 세 번째 둥지가 해금되는 날 */
  thirdFrom: number
}
