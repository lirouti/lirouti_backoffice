/**
 * 레벨 테이블 — 게임 밸런스 상수.
 *
 * ⚠️ **여기 숫자를 바꾸면 이미 그 레벨에 있는 회원이 영향을 받는다.** 그래서 표에
 *    「검수 중」 상태가 있고, 릴리스 전에 기획이 확인한 행만 「적용」 이 된다.
 */

/** 이 행이 실제로 쓰이는가 */
export type LevelStatus = '적용' | '검수 중'

export type Level = {
  /** 1부터 */
  lv: number
  /**
   * **이 레벨에서 다음 레벨로 가는 데** 필요한 경험치.
   *
   * 「이 레벨이 되기까지」 가 아니다 — 둘을 헷갈리면 표가 한 칸씩 밀린다.
   */
  need: number
  /**
   * Lv 1 부터 **이 레벨을 마치기까지** 쌓인 합. `need` 의 러닝 합이다.
   *
   * ⚠️ **누적은 절대로 `need` 보다 작을 수 없다.** 원본은 `need × lv × 0.62` 라는
   *    별개 식으로 만들어서 Lv1 이 「필요 100 · 누적 62」 였다
   *    (docs/ARCHITECTURE.md §24.1).
   */
  total: number
  /** 레벨업할 때 주는 젬 */
  gem: number
  /** 이 레벨에서 열리는 것. 화면에 그대로 찍는 문장이다 */
  unlock: string
  status: LevelStatus
}
