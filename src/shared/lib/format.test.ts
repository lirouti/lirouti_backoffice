import { describe, expect, it } from 'vitest'

import { compact, count, date, gem, num, pct } from './format'

/**
 * ⚠️ **이 describe 는 시간대에 의존한다.** `vite.config.ts` 의 `test.env.TZ` 로
 *    `Asia/Seoul` 에 고정해 두었다 — 고정하지 않으면 오프셋이 붙은 값이 UTC 서쪽
 *    환경에서 하루 밀려 "노트북에서는 통과, CI 에서만 실패"가 된다.
 */
describe('date', () => {
  it('실행 환경이 KST 로 고정돼 있다', () => {
    // 아래 케이스들이 이 전제 위에 서 있으므로, 전제가 깨지면 여기서 먼저 알린다.
    expect(new Date('2026-03-14T09:20:00+09:00').getHours()).toBe(9)
  })

  it('오프셋이 붙은 값을 그대로 읽는다', () => {
    // 지금 목이 주는 모양이다.
    expect(date('2026-03-14T09:20:00+09:00')).toBe('2026년 3월 14일')
  })

  /**
   * 날짜만 있는 값은 **시간대와 무관하게** 같은 날이어야 한다. 위 케이스와 달리
   * 이건 TZ 고정에 기대지 않는다 — `date()` 가 지역 자정으로 직접 만들기 때문이다.
   */
  it('날짜만 있는 값은 시간대에 흔들리지 않는다', () => {
    expect(date('2026-03-14')).toBe(date('2026-03-14'))
    expect(date('2026-03-14')).toContain('3월 14일')
  })

  /**
   * `'YYYY-MM-DD'` 는 **UTC 자정**으로 파싱된다(명세가 그렇다). 지역 시간으로 그대로
   * 찍으면 UTC 보다 뒤진 지역에서 하루 전날이 나온다. 한국에서는 드러나지 않지만
   * **Spring 의 `LocalDate` 가 정확히 이 모양**이라 실서버를 붙이면 들어올 값이다.
   */
  it('날짜만 있는 값을 지역 자정으로 읽는다', () => {
    expect(date('2026-03-14')).toBe('2026년 3월 14일')
  })

  /**
   * `new Date(y, m, d)` 는 범위를 벗어난 값을 거부하지 않고 **굴린다**
   * (`2026-02-31` → 3월 3일). 그러면 "파싱 못 하면 원문" 계약이 깨진다.
   * 타임존을 고치다 실제로 한 번 깨뜨린 자리라 여기서 고정한다.
   */
  it('없는 날짜는 굴리지 않고 원문을 돌려준다', () => {
    expect(date('2026-02-31')).toBe('2026-02-31')
    expect(date('2026-13-01')).toBe('2026-13-01')
    expect(date('2026-02-29')).toBe('2026-02-29') // 2026 은 평년
  })

  it('윤년은 통과시킨다', () => {
    expect(date('2024-02-29')).toBe('2024년 2월 29일')
  })

  /** 생성자는 연도 0~99 를 1900 년대로 매핑한다. `setFullYear` 경로에는 그게 없다. */
  it('연도 0~99 를 1900 년대로 바꾸지 않는다', () => {
    expect(date('0001-01-01')).toBe('1년 1월 1일')
  })

  it('파싱할 수 없으면 원문', () => {
    expect(date('안녕')).toBe('안녕')
    expect(date('')).toBe('')
  })
})

describe('숫자 표기', () => {
  it('천 단위 구분과 단위를 붙인다', () => {
    expect(num(24180)).toBe('24,180')
    expect(count(2916)).toBe('2,916건')
    expect(pct(68.4, 1)).toBe('68.4%')
  })

  it('무료는 0 이 아니라 "무료"로 쓴다', () => {
    // 0 젬과 무료는 화면에서 다른 말이다.
    expect(gem(720)).toBe('720 젬')
    expect(gem(0)).toBe('무료')
  })

  it('KPI 축약은 1000 미만을 그대로 둔다', () => {
    expect(compact(8_400_000)).toBe('8.4M')
    expect(compact(24_180)).toBe('24.2K')
    expect(compact(999)).toBe('999')
  })
})
