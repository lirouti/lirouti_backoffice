/**
 * 디자인 원본(`Component.rng`)의 시드 난수 생성기.
 *
 * 목 데이터는 **결정적**이어야 한다. Math.random 을 쓰면 새로고침할 때마다 숫자가 튀어서
 * 스크린샷 비교도, 디자인 대조도 불가능해진다. 원본 알고리즘을 그대로 유지한다.
 */
export function rng(seed: number): () => number {
  let s = seed * 9301 + 49297
  return () => {
    // JS 의 `%` 는 피연산자 부호를 따라간다 — 음수 시드면 음수가 나오고,
    // `Math.floor(next() * len)` 이 음수 인덱스가 되어 목 데이터가 조용히 깨진다.
    // 양수 시드에서는 `+ M) % M` 이 항등이라 기존 값이 그대로 유지된다.
    s = ((s * 9301 + 49297) % 233280 + 233280) % 233280
    return s / 233280
  }
}
