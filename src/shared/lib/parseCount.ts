/**
 * 「개수·원」 을 받는 입력 칸의 값 읽기.
 *
 * ⚠️ **`replace(/\D/g, '')` 를 쓰지 말 것.** 숫자가 아닌 글자를 **지우고 이어 붙이므로**
 *    오타가 **다른 유효한 값으로 둔갑한다** — `1.5` 가 `15` 로, `-1` 이 `1` 로 저장된다.
 *    젬 수·가격·지급 수량이 조용히 열 배가 되는 자리라 검증도 소용없다: 검증 함수는
 *    소수·음수를 막지만 **그 값이 검증까지 가지 못한다.**
 *    (docs/ARCHITECTURE.md §59.6 — 실제로 폼 9곳에 같은 코드가 있었다)
 */

/**
 * @returns 0 이상의 정수. 읽을 자릿수가 없으면 `0`
 *
 * **첫 번째 숫자 아닌 글자에서 자른다.** 이어 붙이지 않는 것이 요점이다 — `1.5` 는 `1`
 * 이지 `15` 가 아니고, `-1` 은 `0` 이지 `1` 이 아니다.
 *
 * 자릿수 구분 쉼표와 공백은 **지운다** — 표에서 「1,000」 을 복사해 붙여 넣는 경로가 있다.
 *
 * ⚠️ **`NaN` 을 돌려주지 않는다.** 폼이 값을 그대로 다시 그리는 통제된 입력이라,
 *    `NaN` 이면 타이핑 도중에 칸이 「NaN」 으로 바뀌어 친 글자가 사라진다. 대신 못 읽은
 *    글자를 **안 받아들이고** 화면이 즉시 되돌려, 「소수점은 못 쓴다」 가 눈에 보인다.
 */
export function parseCount(raw: string): number {
  const digits = /^\d*/.exec(raw.replace(/[,\s]/g, ''))?.[0] ?? ''
  return digits === '' ? 0 : Number(digits)
}
